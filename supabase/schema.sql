-- ==============================================================================
-- STORED PROCEDURE: get_analytics_summary
-- Replaces Django's AnalyticsSummaryView with a fast native Postgres aggregation.
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.get_analytics_summary(days INT DEFAULT 30)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_cutoff TIMESTAMPTZ;
    v_total_views BIGINT;
    v_total_visitors BIGINT;
    v_series JSONB;
    v_top_pages JSONB;
    v_top_posts JSONB;
    v_top_referrers JSONB;
    v_quotes_trend JSONB;
BEGIN
    -- Only allow authenticated admin calls
    IF auth.role() <> 'authenticated' THEN
        RAISE EXCEPTION 'Unauthorized';
    END IF;

    days := GREATEST(1, LEAST(days, 365));
    v_cutoff := TIMEZONE('utc', NOW()) - (days || ' days')::INTERVAL;

    -- Total views & unique visitors
    SELECT COUNT(*), COUNT(DISTINCT session_key)
    INTO v_total_views, v_total_visitors
    FROM public.page_views
    WHERE created_at >= v_cutoff;

    -- Daily views series
    SELECT COALESCE(JSONB_AGG(JSONB_BUILD_OBJECT('day', to_char(d, 'YYYY-MM-DD'), 'count', c)), '[]'::JSONB)
    INTO v_series
    FROM (
        SELECT DATE_TRUNC('day', created_at) AS d, COUNT(*) AS c
        FROM public.page_views
        WHERE created_at >= v_cutoff
        GROUP BY d
        ORDER BY d
    ) s;

    -- Top 10 pages
    SELECT COALESCE(JSONB_AGG(JSONB_BUILD_OBJECT('path', path, 'count', c)), '[]'::JSONB)
    INTO v_top_pages
    FROM (
        SELECT path, COUNT(*) AS c
        FROM public.page_views
        WHERE created_at >= v_cutoff
        GROUP BY path
        ORDER BY c DESC
        LIMIT 10
    ) p;

    -- Top 10 blog posts
    SELECT COALESCE(JSONB_AGG(JSONB_BUILD_OBJECT('slug', sub.slug, 'title', COALESCE(bp.title, sub.slug), 'count', sub.c)), '[]'::JSONB)
    INTO v_top_posts
    FROM (
        SELECT slug, COUNT(*) AS c
        FROM public.page_views
        WHERE created_at >= v_cutoff AND is_blog_post = true AND slug <> ''
        GROUP BY slug
        ORDER BY c DESC
        LIMIT 10
    ) sub
    LEFT JOIN public.blog_posts bp ON bp.slug = sub.slug;

    -- Top 10 referrers
    SELECT COALESCE(JSONB_AGG(JSONB_BUILD_OBJECT('referrer', referrer, 'count', c)), '[]'::JSONB)
    INTO v_top_referrers
    FROM (
        SELECT referrer, COUNT(*) AS c
        FROM public.page_views
        WHERE created_at >= v_cutoff AND referrer <> ''
        GROUP BY referrer
        ORDER BY c DESC
        LIMIT 10
    ) r;

    -- Quotes trend
    SELECT COALESCE(JSONB_AGG(JSONB_BUILD_OBJECT('day', to_char(d, 'YYYY-MM-DD'), 'count', c)), '[]'::JSONB)
    INTO v_quotes_trend
    FROM (
        SELECT DATE_TRUNC('day', submitted_at) AS d, COUNT(*) AS c
        FROM public.quote_requests
        WHERE submitted_at >= v_cutoff
        GROUP BY d
        ORDER BY d
    ) q;

    RETURN JSONB_BUILD_OBJECT(
        'days', days,
        'total_views', v_total_views,
        'total_visitors', v_total_visitors,
        'series', v_series,
        'top_pages', v_top_pages,
        'top_posts', v_top_posts,
        'top_referrers', v_top_referrers,
        'quotes_trend', v_quotes_trend
    );
END;
$$;


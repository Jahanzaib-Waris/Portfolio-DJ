-- 1. PROFILES TABLE (Singleton)
CREATE TABLE IF NOT EXISTS public.profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'Jerry Dev Studio',
    tagline TEXT DEFAULT 'Practical FlutterFlow fixes, custom Dart code and hands-on help building production mobile apps.',
    bio TEXT DEFAULT 'Mobile application developer specializing in FlutterFlow, Flutter, and scalable cross-platform apps.',
    photo TEXT DEFAULT '',
    resume TEXT DEFAULT '',
    email TEXT DEFAULT 'contact@jerrydevstudio.com',
    github_url TEXT DEFAULT '',
    linkedin_url TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 2. SKILLS TABLE
CREATE TABLE IF NOT EXISTS public.skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT DEFAULT '',
    display_order INT DEFAULT 0
);

-- 3. BLOG POSTS TABLE
CREATE TABLE IF NOT EXISTS public.blog_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    category TEXT DEFAULT 'FlutterFlow Fixes',
    excerpt TEXT DEFAULT '',
    content TEXT NOT NULL DEFAULT '',
    cover_image TEXT DEFAULT '',
    published_date DATE DEFAULT CURRENT_DATE,
    is_published BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_blog_posts_slug ON public.blog_posts (slug);
CREATE INDEX IF NOT EXISTS idx_blog_posts_published ON public.blog_posts (is_published, published_date DESC);

-- 4. PROJECTS TABLE
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT DEFAULT '',
    tech_stack TEXT DEFAULT '',
    thumbnail TEXT DEFAULT '',
    repo_url TEXT DEFAULT '',
    live_url TEXT DEFAULT '',
    display_order INT DEFAULT 0,
    is_featured BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_projects_order ON public.projects (display_order, created_at DESC);

-- 5. QUOTE REQUESTS TABLE
CREATE TABLE IF NOT EXISTS public.quote_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    service TEXT DEFAULT '',
    backend TEXT DEFAULT '',
    budget TEXT DEFAULT '',
    timeline TEXT DEFAULT '',
    project_link TEXT DEFAULT '',
    project_details TEXT NOT NULL,
    submitted_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_quote_requests_submitted ON public.quote_requests (submitted_at DESC);

-- 6. SITE BRANDING (Singleton)
CREATE TABLE IF NOT EXISTS public.site_branding (
    id BIGINT PRIMARY KEY DEFAULT 1,
    site_name TEXT DEFAULT 'Portfolio',
    logo TEXT DEFAULT '',
    favicon TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 7. SITE THEME (Singleton)
CREATE TABLE IF NOT EXISTS public.site_theme (
    id BIGINT PRIMARY KEY DEFAULT 1,
    color_void TEXT DEFAULT '#0A0C16',
    color_panel TEXT DEFAULT '#11142A',
    color_panel_edge TEXT DEFAULT '#232848',
    color_neon_blue TEXT DEFAULT '#38BDF8',
    color_neon_indigo TEXT DEFAULT '#7C6CFF',
    color_accent TEXT DEFAULT '#6D5AF6',
    color_status_green TEXT DEFAULT '#3fb950',
    color_status_red TEXT DEFAULT '#FCA5A5',
    font_display TEXT DEFAULT 'Manrope',
    font_mono TEXT DEFAULT 'Fira Code',
    radius_scale TEXT DEFAULT 'soft',
    shadow_intensity TEXT DEFAULT 'none',
    button_style TEXT DEFAULT 'solid',
    card_style TEXT DEFAULT 'clean',
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 8. PAGE VIEWS TABLE (Analytics)
CREATE TABLE IF NOT EXISTS public.page_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path TEXT NOT NULL,
    referrer TEXT DEFAULT '',
    is_blog_post BOOLEAN DEFAULT FALSE,
    slug TEXT DEFAULT '',
    session_key TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_page_views_created_at ON public.page_views (created_at);
CREATE INDEX IF NOT EXISTS idx_page_views_path ON public.page_views (path);


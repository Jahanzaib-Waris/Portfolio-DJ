-- ==============================================================================
-- radar.sql — server-side Client Radar storage (week 2).
-- Run once in the Supabase SQL Editor. Idempotent: safe to run again.
--
--   * radar_items  : posts fetched by the radar-ingest Edge Function, one row per
--                    source URL, with a shared status (new / dismissed / imported)
--   * crm_leads.source_url : the post a lead came from (duplicate detection)
--
-- The app keeps working without this file: Client Radar falls back to fetching
-- live in the browser until radar_items exists and has been filled.
-- ==============================================================================

ALTER TABLE public.crm_leads ADD COLUMN IF NOT EXISTS source_url TEXT DEFAULT '';
CREATE INDEX IF NOT EXISTS idx_crm_leads_source_url
    ON public.crm_leads (source_url) WHERE source_url <> '';

CREATE TABLE IF NOT EXISTS public.radar_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,                       -- 'hacker_news', 'jobicy', 'remoteok'
    source_label TEXT DEFAULT '',
    source_url TEXT NOT NULL UNIQUE,            -- canonical post URL = dedupe key
    external_id TEXT DEFAULT '',
    company TEXT DEFAULT '',
    title TEXT DEFAULT '',
    location TEXT DEFAULT '',
    employment_type TEXT DEFAULT '',            -- structured type from the source, if any
    type_label TEXT DEFAULT '',                 -- display label ("Contract", "Not specified", ...)
    salary TEXT DEFAULT '',
    email TEXT DEFAULT '',
    website TEXT DEFAULT '',
    description TEXT DEFAULT '',
    full_text TEXT DEFAULT '',
    extra JSONB DEFAULT '{}'::jsonb,            -- tags, apply_url, thread_title, ...
    posted_at TIMESTAMPTZ,
    score INT DEFAULT 0,                        -- score when ingested (freshness decays; the UI recomputes)
    fit TEXT DEFAULT 'unclear',                 -- 'fit' | 'unclear' | 'not_fit'
    status TEXT NOT NULL DEFAULT 'new',         -- 'new' | 'dismissed' | 'imported'
    lead_id BIGINT REFERENCES public.crm_leads(id) ON DELETE SET NULL,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc', NOW()),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc', NOW()),
    notified_at TIMESTAMPTZ                     -- when it was included in a digest
);

CREATE INDEX IF NOT EXISTS idx_radar_items_status_posted ON public.radar_items (status, posted_at DESC);
CREATE INDEX IF NOT EXISTS idx_radar_items_digest ON public.radar_items (status, notified_at, fit, score DESC);
CREATE INDEX IF NOT EXISTS idx_radar_items_last_seen ON public.radar_items (last_seen_at);

ALTER TABLE public.radar_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admin radar_items all" ON public.radar_items;
CREATE POLICY "Admin radar_items all" ON public.radar_items
    FOR ALL TO authenticated USING (true) WITH CHECK (true);
